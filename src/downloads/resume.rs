//! Partial files, validators and the range logic that resumes interrupted transfers.

use super::transfer::{Downloader, Failure};
use super::Artifact;
use crate::hashing::Sha1;
use futures_util::{stream, StreamExt};
use reqwest::{header, Response, StatusCode};
use std::{
    path::{Path, PathBuf},
    sync::atomic::Ordering::Relaxed,
    time::{Duration, SystemTime},
};
use tokio::{
    fs,
    io::{AsyncReadExt, AsyncSeekExt, AsyncWriteExt, BufWriter},
};

/// A stable partial older than this is a download the player abandoned, not one to resume.
pub(super) const PARTIAL_AGE: Duration = Duration::from_secs(7 * 24 * 3600);
pub(super) fn sweep_partials(parent: &Path) {
    let Ok(entries) = std::fs::read_dir(parent) else {
        return;
    };
    let now = SystemTime::now();
    for entry in entries.flatten() {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        if let Some(stem) = name
            .strip_prefix(".sunrise-download-")
            .and_then(|s| s.strip_suffix(".part"))
        {
            // Generated by an older launcher: safe to remove once its process is gone.
            if let Some((pid, nonce)) = stem.split_once('-') {
                if let Ok(pid) = pid.parse::<u32>() {
                    if pid != 0
                        && !nonce.is_empty()
                        && nonce.len() <= 16
                        && nonce.bytes().all(|b| b.is_ascii_hexdigit())
                        && entry.file_type().is_ok_and(|kind| kind.is_file())
                        && !crate::backend::process_alive(pid)
                    {
                        let _ = std::fs::remove_file(entry.path());
                    }
                    continue;
                }
            }
            if stable_stem(stem) && aged(&entry, now) {
                let path = entry.path();
                let _ = std::fs::remove_file(&path);
                let _ = std::fs::remove_dir_all(path.with_extension("segments"));
            }
        } else if let Some(stem) = name
            .strip_prefix(".sunrise-download-")
            .and_then(|s| s.strip_suffix(".segments"))
        {
            if stable_stem(stem) && aged(&entry, now) {
                let path = entry.path();
                let _ = std::fs::remove_dir_all(&path);
                let _ = std::fs::remove_file(path.with_extension("part"));
            }
        }
    }
}

/// A partial this version names: the artifact's SHA-1, a dash, then the destination's SHA-1.
fn stable_stem(stem: &str) -> bool {
    stem.len() == 81
        && stem.as_bytes()[40] == b'-'
        && stem
            .bytes()
            .enumerate()
            .all(|(i, b)| i == 40 || b.is_ascii_hexdigit())
}

fn aged(entry: &std::fs::DirEntry, now: SystemTime) -> bool {
    entry
        .metadata()
        .and_then(|m| m.modified())
        .ok()
        .and_then(|t| now.duration_since(t).ok())
        .is_some_and(|age| age > PARTIAL_AGE)
}
pub(super) fn strong_etag(response: &Response) -> Option<String> {
    response
        .headers()
        .get(header::ETAG)
        .and_then(|s| s.to_str().ok())
        .filter(|s| s.starts_with('"') && s.ends_with('"'))
        .map(str::to_owned)
}
pub(super) async fn valid(
    artifact: &Artifact,
    path: &Path,
    buffer: usize,
) -> Result<bool, Failure> {
    let mut file = match fs::File::open(path).await {
        Ok(file) => file,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(e) => return Err(e.into()),
    };
    let size = file.metadata().await?.len();
    if artifact.size.is_some_and(|expected| size != expected) {
        return Ok(false);
    }
    let mut hash = Sha1::new();
    let mut buffer = vec![0; buffer];
    loop {
        let n = file.read(&mut buffer).await?;
        if n == 0 {
            break;
        }
        hash.update(&buffer[..n]);
    }
    Ok(hash.hex().eq_ignore_ascii_case(&artifact.sha1))
}
/// The `.part` that survives cancellation and restart: named for the destination and the bytes it
/// must become, so a different download never resumes another one's bytes.
pub(super) fn partial_path(artifact: &Artifact) -> PathBuf {
    let parent = artifact
        .path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut hash = crate::hashing::Sha1::new();
    hash.update(artifact.path.as_os_str().as_encoded_bytes());
    parent.join(format!(
        ".sunrise-download-{}-{}.part",
        artifact.sha1.to_ascii_lowercase(),
        hash.hex()
    ))
}

impl Downloader {
    /// A failed stream retains only bytes flushed to disk. Reusing them requires a strong ETag.
    async fn piece(
        &self,
        artifact: &Artifact,
        path: &Path,
        bounds: Option<(u64, u64, u64)>,
        validator: Option<&str>,
        file_offset: u64,
    ) -> Result<Option<String>, Failure> {
        let mut copied = 0;
        let mut hash = crate::hashing::Sha1::new();
        let mut hashed = true;
        let mut validator = validator.map(str::to_owned);
        let (start, end, total) = bounds.unwrap_or((
            0,
            artifact.size.unwrap_or(0).saturating_sub(1),
            artifact.size.unwrap_or(0),
        ));
        for attempt in 0..=self.config.retries {
            if attempt > 0 && (validator.is_none() || total == 0) {
                copied = 0;
            }
            if copied > 0 && total > 0 && copied == end - start + 1 {
                return Ok(hashed.then(|| hash.hex()));
            }
            let ranged = bounds.is_some() || (copied > 0 && validator.is_some() && total > 0);
            // A ranged piece covers only its slice, so its hash is not the artifact's. A retry
            // that starts over resets the file, and the hash with it.
            if ranged {
                hashed = false;
            } else {
                hash = crate::hashing::Sha1::new();
                hashed = true;
            }
            let result = async {
                let mut connection = self
                    .request(
                        &artifact.url,
                        ranged.then_some((start + copied, end)),
                        validator.as_deref(),
                    )
                    .await?;
                let response = &mut connection.response;
                if ranged {
                    let expected = format!("bytes {}-{end}/{total}", start + copied);
                    if response.status() != StatusCode::PARTIAL_CONTENT
                        || response
                            .headers()
                            .get(header::CONTENT_RANGE)
                            .and_then(|v| v.to_str().ok())
                            != Some(expected.as_str())
                    {
                        return Err(Failure::range(crate::i18n::tr(
                            "Server ignored or changed the requested byte range",
                        )));
                    }
                } else if response.status() != StatusCode::OK {
                    return Err(Failure::range(crate::i18n::tr(
                        "Unexpected partial response",
                    )));
                }
                let tag = strong_etag(response);
                if validator.as_ref().is_some_and(|v| tag.as_ref() != Some(v)) {
                    return Err(Failure::range(crate::i18n::tr(
                        "Resource changed during transfer",
                    )));
                }
                if validator.is_none() {
                    validator = tag;
                }
                let expected = if ranged {
                    Some(end - start + 1 - copied)
                } else {
                    artifact.size.or(response.content_length())
                };
                if expected
                    .zip(response.content_length())
                    .is_some_and(|(a, b)| a != b)
                {
                    return Err(Failure::range(crate::i18n::tr(
                        "Inconsistent Content-Length",
                    )));
                }
                let mut file = fs::OpenOptions::new().write(true).open(path).await?;
                if file_offset == 0 && copied == 0 {
                    file.set_len(0).await?;
                }
                file.seek(std::io::SeekFrom::Start(file_offset + copied))
                    .await?;
                let mut writer = BufWriter::with_capacity(self.config.buffer, file);
                let mut received = 0;
                let body = async {
                    while let Some(chunk) = response.chunk().await? {
                        if expected.is_some_and(|n| received + chunk.len() as u64 > n) {
                            return Err(Failure::range(crate::i18n::tr(
                                "Response exceeds expected length",
                            )));
                        }
                        writer.write_all(&chunk).await?;
                        if hashed {
                            hash.update(&chunk);
                        }
                        received += chunk.len() as u64;
                        self.metrics
                            .counters
                            .bytes
                            .fetch_add(chunk.len() as u64, Relaxed);
                    }
                    if expected.is_some_and(|n| received != n) {
                        return Err(Failure::transient("Truncated response"));
                    }
                    Ok(())
                }
                .await;
                writer.flush().await?;
                copied += received;
                body
            }
            .await;
            match result {
                Ok(()) => return Ok(hashed.then(|| hash.hex())),
                Err(e) if e.retry && attempt < self.config.retries => {
                    self.pause(attempt, e.after).await
                }
                Err(e) => return Err(e),
            }
        }
        unreachable!()
    }
    pub(super) async fn transfer(
        &self,
        artifact: &Artifact,
        path: &Path,
    ) -> Result<Option<String>, Failure> {
        if let Some(size) = artifact.size.filter(|&size| {
            size >= self.config.threshold
                && size > self.config.minimum_segment
                && self.config.segments > 1
        }) {
            let mut attempt = 0;
            let probe = loop {
                match self.request(&artifact.url, Some((0, 0)), None).await {
                    Err(e) if e.retry && attempt < self.config.retries => {
                        self.pause(attempt, e.after).await;
                        attempt += 1;
                    }
                    result => break result,
                }
            };
            if let Ok(mut probe) = probe {
                let expected = format!("bytes 0-0/{size}");
                if probe.response.status() == StatusCode::PARTIAL_CONTENT
                    && probe
                        .response
                        .headers()
                        .get(header::CONTENT_RANGE)
                        .and_then(|v| v.to_str().ok())
                        == Some(expected.as_str())
                {
                    let validator = strong_etag(&probe.response);
                    let valid = probe
                        .response
                        .chunk()
                        .await
                        .is_ok_and(|c| c.is_some_and(|c| c.len() == 1))
                        && probe.response.chunk().await.is_ok_and(|c| c.is_none());
                    drop(probe);
                    if valid {
                        // More chunks than connections let a fast stream take over a slow one's remaining work.
                        let chunk = self
                            .config
                            .minimum_segment
                            .max(size.div_ceil((self.config.segments * 4) as u64));
                        let chunks = path.with_extension("segments");
                        fs::create_dir_all(&chunks).await?;
                        let count = size.div_ceil(chunk);
                        let result = stream::iter((0..count).map(|i| {
                            let file = chunks.join(format!("{i}.seg"));
                            let (start, end) = (i * chunk, ((i + 1) * chunk).min(size) - 1);
                            let validator = validator.clone();
                            async move {
                                // A chunk from an interrupted run is already complete: keep it.
                                if fs::metadata(&file)
                                    .await
                                    .is_ok_and(|m| m.len() == end - start + 1)
                                {
                                    return Ok(());
                                }
                                fs::OpenOptions::new()
                                    .create(true)
                                    .truncate(false)
                                    .write(true)
                                    .open(&file)
                                    .await?;
                                self.piece(
                                    artifact,
                                    &file,
                                    Some((start, end, size)),
                                    validator.as_deref(),
                                    0,
                                )
                                .await
                                .map(|_| ())
                            }
                        }))
                        .buffer_unordered(self.config.segments)
                        .collect::<Vec<_>>()
                        .await
                        .into_iter()
                        .collect::<Result<Vec<_>, _>>();
                        match result {
                            Ok(_) => {
                                let mut output = fs::OpenOptions::new()
                                    .create(true)
                                    .write(true)
                                    .truncate(true)
                                    .open(path)
                                    .await?;
                                for i in 0..count {
                                    let mut part =
                                        fs::File::open(chunks.join(format!("{i}.seg"))).await?;
                                    tokio::io::copy(&mut part, &mut output).await?;
                                }
                                output.flush().await?;
                                drop(output);
                                let _ = fs::remove_dir_all(&chunks).await;
                                return Ok(None);
                            }
                            Err(e) if e.range => {
                                let _ = fs::remove_dir_all(&chunks).await;
                            }
                            Err(e) => return Err(e),
                        }
                    }
                }
            } else if let Err(e) = probe {
                if !e.range {
                    return Err(e);
                }
            }
        }
        let mut have = fs::metadata(path).await.map(|m| m.len()).unwrap_or(0);
        if let Some(size) = artifact.size.filter(|&size| size > 0) {
            // A finished .part only needs its hash checked by the caller.
            if have == size {
                return Ok(None);
            }
            if have > size {
                have = 0;
            }
            if have > 0 {
                match self
                    .piece(artifact, path, Some((have, size - 1, size)), None, have)
                    .await
                {
                    Ok(_) => return Ok(None),
                    Err(e) if e.range => {}
                    Err(e) => return Err(e),
                }
            }
        }
        fs::OpenOptions::new()
            .write(true)
            .open(path)
            .await?
            .set_len(0)
            .await?;
        match self.piece(artifact, path, None, None, 0).await {
            Err(e) if e.range => {
                fs::OpenOptions::new()
                    .write(true)
                    .open(path)
                    .await?
                    .set_len(0)
                    .await?;
                self.piece(artifact, path, None, None, 0).await
            }
            result => result,
        }
    }
}
